'use strict'
const assert=require('node:assert/strict')
const {chromium}=require(process.env.UHL_PLAYWRIGHT || 'playwright')
const base=process.env.UHL_REVIEW_TEST_ORIGIN ?? 'http://127.0.0.1:55831'

async function run() {
 const browser=await chromium.launch(process.env.UHL_CHROME?{executablePath:process.env.UHL_CHROME}:{})
 try {
  const p=await browser.newPage({viewport:{width:390,height:900}})
  await p.addInitScript(()=>localStorage.setItem('uhl_cookie_consent','necessary_only'))
  const visit=async path=>assert.equal((await p.goto(base+path)).status(),200,path)
  await visit('/review-acceptance')
  await p.getByRole('button',{name:'Als Test-Hiker'}).click()
  await p.getByText('Test-Hiker ist aktiv.',{exact:true}).waitFor()
  await visit('/de/events/abnahme-felsenweg-2026')
  const overview=p.locator('details#reviews')
  await overview.waitFor()
  assert.equal(await overview.getAttribute('open'),null)
  await p.locator('a[href="#reviews"]').click()
  assert.equal(await overview.evaluate(el=>el.open),true)
  assert.equal(await overview.locator('dl').first().locator('dt').count(),6)
  assert.equal(await p.getByText('Ich möchte diese Veranstaltung bewerten.',{exact:true}).count(),0)
  assert.ok(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))
  await visit('/review-acceptance/activity')
  const opt=p.getByRole('checkbox',{name:'Ich möchte diese Veranstaltung bewerten.'})
  await opt.waitFor()
  assert.equal(await opt.isChecked(),false)
  await opt.check()
  const ratings=await p.getByRole('radio',{name:'4/5 Sterne',exact:true}).all()
  assert.equal(ratings.length,7)
  for(const radio of ratings) await radio.locator('..').click()
  await p.getByRole('textbox',{name:'Kommentar (optional)'}).first().fill('Abnahme der Einreichung')
  await p.getByPlaceholder('z. B. 08:34').fill('08:45')
  await p.locator('input[type=file]').setInputFiles({name:'test.png',mimeType:'image/png',buffer:Buffer.from([137,80,78,71,13,10,26,10])})
  await p.getByRole('button',{name:'Wanderung einreichen',exact:true}).click()
  await p.getByText('Deine Wanderung wurde erfolgreich eingereicht.',{exact:true}).waitFor()
  await visit('/review-acceptance/activity?edit=1')
  await p.getByRole('button',{name:'Eintrag bearbeiten',exact:true}).click()
  await p.getByRole('button',{name:'Überarbeiten',exact:true}).click()
  assert.equal(await p.getByRole('radio',{name:'4/5 Sterne',exact:true}).first().isChecked(),true)
  await p.getByRole('textbox',{name:'Kommentar (optional)'}).first().fill('Neue geprüfte Testfassung')
  await p.getByRole('button',{name:'Bewertung einreichen',exact:true}).click()
  await p.getByText('Überarbeitung in Prüfung',{exact:true}).waitFor()
  await visit('/review-acceptance')
  await p.getByRole('button',{name:'Admin-Moderation öffnen',exact:true}).click()
  await p.getByRole('heading',{name:'Veranstaltungsbewertungen moderieren'}).waitFor()
  await p.getByText('Neue geprüfte Testfassung',{exact:true}).waitFor()
  await visit('/de/leaderboard/event-reviews')
  await p.getByRole('heading',{name:'Veranstaltungsranking'}).waitFor()
  await p.getByRole('link',{name:/Felsenweg/}).click()
  await p.locator('details#reviews[open]').waitFor()
  await visit('/de/leaderboard/organizer-reviews')
  await p.getByRole('link',{name:/Wanderwerk Felsental/}).click()
  await p.getByRole('heading',{name:'Wanderwerk Felsental'}).waitFor()
  console.log('Activity entry, editing, moderation and public review layout passed')
 }finally{await browser.close()}
}
run().catch(error=>{console.error(error);process.exitCode=1})
